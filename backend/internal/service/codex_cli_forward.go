type codexCLITaskRuntime interface {
	Status(context.Context) codexcli.Status
	RunTask(context.Context, codexcli.TaskRequest) (codexcli.TaskResult, error)
}

type managedCodexCLITaskRuntime struct{}

func (managedCodexCLITaskRuntime) Status(ctx context.Context) codexcli.Status {
	return codexcli.DefaultManager().Status(ctx)
}
func (managedCodexCLITaskRuntime) RunTask(ctx context.Context, request codexcli.TaskRequest) (codexcli.TaskResult, error) {
	return codexcli.RunTask(ctx, request)
}

func (s *OpenAIGatewayService) forwardCodexCLITask(ctx context.Context, c *gin.Context, account *Account, body []byte) (*OpenAIForwardResult, error) {
	return s.forwardCodexCLITaskWithRuntime(ctx, c, account, body, managedCodexCLITaskRuntime{})
}

func (s *OpenAIGatewayService) forwardCodexCLITaskWithRuntime(ctx context.Context, c *gin.Context, account *Account, body []byte, runtime codexCLITaskRuntime) (*OpenAIForwardResult, error) {
	start := time.Now()
	request, err := ParseCodexCLITaskRequest(body)
	fail := func(status int, code string) (*OpenAIForwardResult, error) {
		payload := gin.H{"error": gin.H{"type": "codex_cli_error", "code": code, "message": "Codex CLI task could not complete"}}
		if c.Writer.Written() && strings.HasPrefix(c.Writer.Header().Get("Content-Type"), "text/event-stream") {
			encoded, _ := json.Marshal(payload)
			_, _ = c.Writer.Write(append(append([]byte("event: error\ndata: "), encoded...), []byte("\n\n")...))
			c.Writer.Flush()
		} else {
			c.JSON(status, payload)
		}
		return nil, errors.New(code)
	}
	if err != nil {
		return fail(http.StatusBadRequest, "unsupported_task_request")
	}
	if !CodexCLITaskAccountEnabled(account) {
		return fail(http.StatusServiceUnavailable, "cli_account_unavailable")
	}
	if _, err := account.StrictProxyURL(); err != nil {
		return fail(http.StatusBadGateway, "cli_proxy_unavailable")
	}
	model := account.GetMappedModel(request.Model)
	if model == "" {
		model = request.Model
	}
	if err := s.validateCodexCLIStandardTierPolicy(ctx, account, model); err != nil {
		MarkOpsClientBusinessLimited(c, OpsClientBusinessLimitedReasonLocalPolicyDenied)
		return fail(http.StatusForbidden, "cli_service_tier_policy_denied")
	}
	status := runtime.Status(ctx)
	if !status.ExecutionAvailable {
		return fail(http.StatusServiceUnavailable, "cli_runtime_unavailable")
	}
	token, _, err := s.GetAccessToken(ctx, account)
	if err != nil {
		return fail(http.StatusBadGateway, "cli_credential_unavailable")
	}
	ctx = withRequestCredentialOwner(ctx, account, token)
	defer bindRequestCredentialOwnerContext(ctx, c)()
	owner, ok := requestCredentialOwner(ctx, account)
	if !ok || !CodexCLITaskAccountEnabled(owner) {
		return fail(http.StatusConflict, "cli_credential_owner_changed")
	}
	configuration, err := CodexCLIConfigurationForAccount(owner)
	if err != nil {
		return fail(http.StatusBadRequest, "cli_config_invalid")
	}
	ownerModel := owner.GetMappedModel(request.Model)
	if ownerModel == "" {
		ownerModel = request.Model
	}
	if ownerModel != model {
		if err := s.validateCodexCLIStandardTierPolicy(ctx, owner, ownerModel); err != nil {
			MarkOpsClientBusinessLimited(c, OpsClientBusinessLimitedReasonLocalPolicyDenied)
			return fail(http.StatusForbidden, "cli_service_tier_policy_denied")
		}
		model = ownerModel
	}
	auth, err := BuildCodexCLIAuthJSON(owner)
	if err != nil {
		return fail(http.StatusBadRequest, "cli_auth_incomplete")
	}
	headers := make(http.Header)
	s.applyOpenAIOutboundIdentity(ctx, owner, headers, true)
	headers.Set("Chatgpt-Account-Id", owner.GetChatGPTAccountID())
	config, reasoningEffort, err := codexCLITaskConfig(configuration.ConfigTOML, request, headers)
	if err != nil {
		return fail(http.StatusBadRequest, "cli_config_invalid")
	}
	run, home, workspace, err := materializeCodexCLITask("", owner.ID, auth, config)
	if err != nil {
		return fail(http.StatusInternalServerError, "cli_state_unavailable")
	}
	defer func() { _ = os.RemoveAll(run) }() //nolint:gosec // run is generated by MkdirTemp beneath the checked server data root, never a caller path.
	env := map[string]string{"SUB2API_CODEX_ACCESS_TOKEN": token}
	proxy, err := requestCredentialOwnerProxyURL(ctx, owner)
	if err != nil {
		return fail(http.StatusBadGateway, "cli_proxy_unavailable")
	}
	if proxy != "" {
		env["HTTP_PROXY"], env["HTTPS_PROXY"], env["ALL_PROXY"] = proxy, proxy, proxy
	}
	SetOpsUpstreamModel(c, model)
	SetActualOpenAIUpstreamEndpoint(c, openAIResponsesUpstreamEndpoint)
	task, taskErr := runtime.RunTask(ctx, codexcli.TaskRequest{Runtime: status, Home: home, WorkDir: workspace, Prompt: request.Input, Model: model, ExtraEnv: env})
	if !task.Started && taskErr != nil {
		return fail(http.StatusBadGateway, "cli_process_unavailable")
	}
	id := "resp_" + strings.ReplaceAll(uuid.NewString(), "-", "")
	result := codexCLITaskForwardResult(task, request, model, id, time.Since(start))
	// Billing and usage records must retain the effort sent to the CLI,
	// including an account default and partial usage after task failure.
	result.ReasoningEffort = reasoningEffort
	if taskErr != nil {
		result.UsageIncomplete = true
		result.ClientDisconnect = ctx.Err() != nil
		_, _ = fail(http.StatusBadGateway, "cli_task_failed")
		// A normal error is terminal. Returning a failover error here could
		// replay shell/file side effects on another account.
		return result, taskErr
	}
	response := codexCLITaskResponse(task, request.Model, id)
	if request.Stream {
		c.Header("Content-Type", "text/event-stream")
		c.Header("Cache-Control", "no-cache")
		encoded, _ := json.Marshal(gin.H{"type": "response.completed", "response": response})
		_, err = c.Writer.Write(append(append([]byte("event: response.completed\ndata: "), encoded...), []byte("\n\ndata: [DONE]\n\n")...))
		c.Writer.Flush()
	} else {
		c.JSON(http.StatusOK, response)
	}
	return result, err
}

// The pinned CLI may discard a paid tier according to its model catalog, and
// exec JSONL does not report the actual tier. Standard tasks explicitly disable
// catalog tier defaults. A shared policy requiring Fast must reject before any
// credential acquisition rather than silently bypass policy or bill a guess.
func (s *OpenAIGatewayService) validateCodexCLIStandardTierPolicy(ctx context.Context, account *Account, model string) error {
	decisionBody, err := json.Marshal(map[string]string{"model": model})
	if err != nil {
		return err
	}
	decisionBody, err = s.applyOpenAIFastPolicyToBody(ctx, account, model, decisionBody)
	if err != nil {
		return err
	}
	if extractOpenAIServiceTierFromBody(decisionBody) != nil {
		return errors.New("codex CLI tasks support standard service tier only")
	}
	return nil
}

// The managed overlay owns authentication, destination and identity. Account
// sandbox settings remain effective. Approval policy is validated as never
// because the reviewed exec interface is noninteractive.
func codexCLITaskConfig(accountConfig string, request CodexCLITaskRequest, headers http.Header) ([]byte, *string, error) {
	var config map[string]any
	if err := toml.Unmarshal([]byte(accountConfig), &config); err != nil {
		return nil, nil, err
	}
	// Full Access is the project default even when an edited configuration
	// contains only unrelated settings. Explicit account sandbox choices win.
	if _, supplied := config["sandbox_mode"]; !supplied {
		config["sandbox_mode"] = "danger-full-access"
	}
	config["model_provider"] = "sub2api_managed_codex"
	config["cli_auth_credentials_store"] = "file"
	// Official 0.165's explicit default sentinel suppresses model-catalog
	// service-tier defaults. Paid tiers cannot be established by exec JSONL.
	config["service_tier"] = "default"
	config["check_for_update_on_startup"] = false
	config["analytics"] = map[string]any{"enabled": false}
	config["feedback"] = map[string]any{"enabled": false}
	config["otel"] = map[string]any{"exporter": "none", "trace_exporter": "none", "metrics_exporter": "none", "log_user_prompt": false}
	config["web_search"] = "disabled"
	disableCodexCLITaskRemoteFeatures(config)
	cloud, ok := config["cloud"].(map[string]any)
	if !ok {
		cloud = make(map[string]any)
		config["cloud"] = cloud
	}
	cloud["skills"] = map[string]any{"enabled": false}
	if request.Instructions != "" {
		config["developer_instructions"] = request.Instructions
	}
	if request.ReasoningEffort != "" {
		config["model_reasoning_effort"] = request.ReasoningEffort
	}
	trustedHeaders := map[string]string{}
	for name, values := range headers {
		if len(values) > 0 {
			trustedHeaders[name] = values[0]
		}
	}
	config["model_providers"] = map[string]any{"sub2api_managed_codex": map[string]any{
		"name": "Sub2API managed Codex", "base_url": strings.TrimSuffix(chatgptCodexURL, "/responses"),
		"wire_api": "responses", "env_key": "SUB2API_CODEX_ACCESS_TOKEN", "requires_openai_auth": false,
		"supports_websockets": false, "request_max_retries": 0, "stream_max_retries": 0, "http_headers": trustedHeaders,
	}}
	encoded, err := toml.Marshal(config)
	effort, _ := config["model_reasoning_effort"].(string)
	return encoded, optionalTrimmedStringPtr(effort), err
}

func disableCodexCLITaskRemoteFeatures(config map[string]any) {
	features, ok := config["features"].(map[string]any)
	if !ok {
		features = make(map[string]any)
		config["features"] = features
	}
	for _, key := range []string{"plugins", "remote_plugin", "plugin_sharing", "apps", "tool_suggest", "recommended_plugins"} {
		features[key] = false
	}
}

func codexCLITaskForwardResult(task codexcli.TaskResult, request CodexCLITaskRequest, model, id string, duration time.Duration) *OpenAIForwardResult {
	return &OpenAIForwardResult{RequestID: id, ResponseID: id, Model: request.Model, UpstreamModel: model,
		Stream: request.Stream, Duration: duration, UpstreamEndpoint: openAIResponsesUpstreamEndpoint,
		UsageSource: "codex_cli_task", UsageIncomplete: task.UsageIncomplete,
		Usage: OpenAIUsage{InputTokens: int(task.Usage.InputTokens), OutputTokens: int(task.Usage.OutputTokens), CacheReadInputTokens: int(task.Usage.CachedInputTokens), CacheCreationInputTokens: int(task.Usage.CacheWriteInputTokens)}}
}

func codexCLITaskResponse(task codexcli.TaskResult, model, id string) gin.H {
	return gin.H{"id": id, "object": "response", "created_at": time.Now().Unix(), "status": "completed", "model": model,
		"output": []any{gin.H{"id": "msg_" + strings.TrimPrefix(id, "resp_"), "type": "message", "role": "assistant", "status": "completed", "content": []any{gin.H{"type": "output_text", "text": task.Output, "annotations": []any{}}}}},
		"usage": gin.H{"input_tokens": task.Usage.InputTokens, "output_tokens": task.Usage.OutputTokens,
			"total_tokens":         task.Usage.InputTokens + task.Usage.OutputTokens,
			"input_tokens_details": gin.H{"cached_tokens": task.Usage.CachedInputTokens}, "output_tokens_details": gin.H{"reasoning_tokens": task.Usage.ReasoningOutputTokens}}}
}

func materializeCodexCLITask(root string, accountID int64, auth, config []byte) (run, home, workspace string, err error) {
	if accountID <= 0 {
		return "", "", "", errors.New("invalid CLI credential owner")
	}
	if root == "" {
		root = strings.TrimSpace(os.Getenv("DATA_DIR"))
		if root == "" {
			root = "./data"
		}
	}
	root, err = filepath.Abs(root)
	if err != nil {
		return
	}
	directory := filepath.Join(root, "codex", "accounts", strconv.FormatInt(accountID, 10), "runs")
	if err = privateCodexCLIDirectory(directory); err != nil {
		return
	}
	run, err = os.MkdirTemp(directory, "task-") //nolint:gosec // directory combines server DATA_DIR, fixed segments and a positive decimal account ID.
	if err != nil {
		return
	}
	defer func() {
		if err != nil {
			_ = os.RemoveAll(run) //nolint:gosec // only this invocation's MkdirTemp path is removed after failed materialization.
		}
	}()
	home, workspace = filepath.Join(run, "home"), filepath.Join(run, "workspace")
	for _, path := range []string{home, workspace} {
		if err = os.Mkdir(path, 0700); err != nil { //nolint:gosec // path is generated from a checked root, integer owner and MkdirTemp, never caller paths.
			return
		}
	}
	if err = os.WriteFile(filepath.Join(home, "auth.json"), auth, 0600); err != nil { //nolint:gosec // home is a fresh private directory generated below the checked account root.
		return
	}
	err = os.WriteFile(filepath.Join(home, "config.toml"), config, 0600) //nolint:gosec // home is a fresh private directory generated below the checked account root.
	return
}

func privateCodexCLIDirectory(directory string) error {
	// Reject symlink components before writing account secrets. Full Access
	// tasks share a service user: this is defensive file handling, not sandboxing.
	var paths []string
	for path := directory; path != filepath.Dir(path); path = filepath.Dir(path) {
		paths = append(paths, path)
	}
	for i := len(paths) - 1; i >= 0; i-- {
		path := paths[i]
		info, err := os.Lstat(path) //nolint:gosec // inspect ancestors of the server-configured data root and generated integer account path to reject symlinks.
		if os.IsNotExist(err) {
			if err = os.Mkdir(path, 0700); err != nil && !os.IsExist(err) { //nolint:gosec // missing ancestors belong to the trusted data root and generated account path.
				return err
			}
			info, err = os.Lstat(path) //nolint:gosec // recheck the same generated ancestor after creation to reject symlink races.
		}
		if err != nil {
			return err
		}
		if !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
			return errors.New("unsafe CLI data directory")
		}
	}
	return os.Chmod(directory, 0700) //nolint:gosec // the generated account runs directory and every ancestor were checked above; no caller path segments are accepted.
}
